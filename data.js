// ===== اكواد الخصم  =====


function getAutoDiscount(cart, couponCode) {
  const totalItems = cart.reduce((s, i) => s + i.qty, 0);

  // خصم تلقاىي حسب الكميه
  if (totalItems >= 5) {
    return { discount: 0.20, label: 'خصم تلقائي ٢٠٪ (٥ منتجات أو أكثر) 🎉' };
  }
  if (totalItems >= 2) {
    return { discount: 0.15, label: 'خصم تلقائي ١٥٪ (٢–٤ منتجات) 🌿' };
  }

  // كود WELCOME للطلب الأول
  const orders = JSON.parse(localStorage.getItem('bh_orders') || '[]');
  const isFirstOrder = orders.length === 0;
  if (couponCode && couponCode.toUpperCase() === 'WELCOME' && isFirstOrder) {
    return { discount: 0.10, label: 'كود WELCOME — خصم ١٠٪ على طلبك الأول 🎁' };
  }

  return null;
}